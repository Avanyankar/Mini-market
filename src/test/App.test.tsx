import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { App } from '../App'
import { cartKey, themeKey } from '../state'

describe('Мини-маркет', () => {
  it('uses system preference, persists theme changes and restores the selection', async () => {
    const user = userEvent.setup()
    vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: true })))
    const { unmount } = render(<App />)
    expect(window.matchMedia).toHaveBeenCalledWith('(prefers-color-scheme: dark)')
    expect(screen.getByRole('button', { name: 'Тёмная' })).toHaveAttribute('aria-pressed', 'true')
    await user.click(screen.getByRole('button', { name: 'Светлая' }))
    expect(localStorage.getItem(themeKey)).toBe('light')
    await user.click(screen.getByRole('button', { name: 'Сепия' }))
    expect(localStorage.getItem(themeKey)).toBe('sepia')
    unmount()
    render(<App />)
    expect(screen.getByRole('button', { name: 'Сепия' })).toHaveAttribute('aria-pressed', 'true')
  })

  it('loads, filters by genre, searches by author and title, and resets an empty result', async () => {
    const user = userEvent.setup()
    render(<App />)
    expect(screen.getByRole('status')).toHaveTextContent('Загрузка каталога')
    expect(await screen.findAllByRole('article')).toHaveLength(12)
    await user.click(screen.getByRole('button', { name: 'Фантастика' }))
    expect(screen.getByRole('status')).toHaveTextContent('Загрузка каталога')
    expect(await screen.findAllByRole('article')).toHaveLength(3)

    const search = screen.getByRole('searchbox')
    await user.type(search, 'брэдбери')
    expect(screen.getAllByRole('article')).toHaveLength(1)
    expect(screen.getByRole('heading', { name: '451° по Фаренгейту' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Очистить поиск' }))
    expect(search).toHaveFocus()
    await user.type(search, 'дюна')
    expect(screen.getByRole('heading', { name: 'Дюна' })).toBeVisible()
    await user.type(search, 'xyz')
    expect(screen.getByRole('heading', { name: 'Книги не найдены' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Сбросить фильтры' }))
    expect(search).toHaveFocus()
    expect(search).toHaveValue('')
    expect(await screen.findAllByRole('article')).toHaveLength(12)
  })

  it('adds a book across a filter transition, updates quantity, persists and removes it', async () => {
    const user = userEvent.setup()
    const { unmount } = render(<App />)
    const [first] = await screen.findAllByRole('article')
    const add = within(first).getByRole('button', { name: 'В корзину' })
    await user.click(add)
    expect(add).toHaveAttribute('aria-busy', 'true')
    await user.click(screen.getByRole('button', { name: 'Фантастика' }))
    const opener = await screen.findByRole('button', { name: 'Корзина 1' })
    await user.click(opener)
    const cart = within(screen.getByRole('dialog', { name: 'Корзина' }))
    expect(opener).toHaveAttribute('aria-expanded', 'true')
    expect(cart.getByRole('button', { name: 'Закрыть корзину' })).toHaveFocus()
    await user.click(cart.getByRole('button', { name: /Увеличить количество/ }))
    expect(cart.getByText('Итого · 2 шт.')).toBeVisible()
    expect(cart.getByText(/1\s380\s₽/)).toBeVisible()
    await user.click(cart.getByRole('button', { name: /Уменьшить количество/ }))
    expect(localStorage.getItem(cartKey)).toBe('{"master":1}')
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true }))
    expect(opener).toHaveFocus()
    unmount()
    render(<App />)
    await user.click(screen.getByRole('button', { name: 'Корзина 1' }))
    const restored = within(screen.getByRole('dialog'))
    await user.click(restored.getByRole('button', { name: /Удалить/ }))
    expect(restored.getByText('Корзина пуста')).toBeVisible()
    expect(localStorage.getItem(cartKey)).toBe('{}')
  })

  it('clears the basket and confirms simulated checkout', async () => {
    localStorage.setItem(cartKey, '{"master":1,"dune":2}')
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: 'Корзина 3' }))
    const cart = within(screen.getByRole('dialog'))
    const checkout = cart.getByRole('button', { name: 'Оформить заказ' })
    await user.click(checkout)
    expect(checkout).toBeDisabled()
    expect(await cart.findByText('Заказ успешно оформлен!')).toBeVisible()
    expect(localStorage.getItem(cartKey)).toBe('{}')
    await user.click(cart.getByRole('button', { name: 'Вернуться в каталог' }))
    const [first] = await screen.findAllByRole('article')
    await user.click(within(first).getByRole('button', { name: 'В корзину' }))
    await user.click(await screen.findByRole('button', { name: 'Корзина 1' }))
    expect(cart.queryByText('Заказ успешно оформлен!')).not.toBeInTheDocument()
    await user.click(cart.getByRole('button', { name: 'Очистить корзину' }))
    expect(cart.getByText('Корзина пуста')).toBeVisible()
  })
})
